// Comparison Operators
let a = 5;
let b = 3;
//Only value check (==, !=)
console.log("5 == 3", a == b); //false
console.log("5 != 3", a != b); //true

//Datatype as well as value check (===, !==)
let c = "5";
let d = 5;
console.log("5 === 5", c === d);
console.log("5 !== 5", c !== d);

//check for (<, >)
console.log("5 > 3", a > b);
console.log("5 < 3", a < b);

//check for (<=, >=)
console.log("5 <= 3", a <= b);
console.log("5 >= 3", a >= b);